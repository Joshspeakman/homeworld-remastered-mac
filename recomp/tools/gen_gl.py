"""gen_gl.py <out.c>: guest-ABI wrappers for every OpenGL entry point in the SDK's headers (gl.h, glext.h, gl3.h).

Each wrapper reads its arguments from the guest stack (cdecl, 4-byte slots; GLdouble and 64-bit integers take two),
turns guest pointers into host pointers and calls the GL implementation through the `glp` table (runtime/mac/gl.c
fills it: Apple's OpenGL as the reference backend, or the port's own GL on Metal). Results: integers in eax, floats
and doubles in st(0). Entry points whose pointer arguments are not plain guest memory (buffer offsets, string
arrays, mapped buffers, sync objects, callbacks, returned strings) are written by hand in gl.c and skipped here.
Both spellings are registered: "_glFoo" (a direct import) and "glFoo" (SDL_GL_GetProcAddress)."""
import sys, re, subprocess
SDK = subprocess.run(['xcrun', '--show-sdk-path'], capture_output=True, text=True).stdout.strip()
HDR = SDK + '/System/Library/Frameworks/OpenGL.framework/Headers/'
MANUAL = set(open(__file__.replace('gen_gl.py', '../runtime/mac/gl_manual.txt')).read().split())

def parse(path):
    src = open(path).read()
    src = re.sub(r'/\*.*?\*/', ' ', src, flags=re.S)
    src = re.sub(r'#.*', ' ', src)
    out = {}
    for m in re.finditer(r'(?:extern|GLAPI)\s+([\w\s\*]+?)\s*(?:APIENTRY\s+)?\b(gl[A-Z]\w*)\s*\(([^;{]*?)\)\s*(?:\w+\s*\([^)]*\)\s*)*;', src):
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
        ret = re.sub(r'\b(extern|GLAPI|APIENTRY)\b', '', ret).strip()
        out[name] = (ret, args)
    return out

fns = {}
for h in ('gl.h', 'glext.h', 'gl3.h'):
    for k, v in parse(HDR + h).items(): fns.setdefault(k, v)

INT = {'GLenum', 'GLboolean', 'GLbitfield', 'GLbyte', 'GLshort', 'GLint', 'GLsizei', 'GLubyte', 'GLushort', 'GLuint',
       'GLchar', 'GLcharARB', 'GLhalfARB', 'GLhalf', 'GLclampx', 'GLfixed', 'int', 'unsigned int', 'GLintptr', 'GLsizeiptr',
       'GLintptrARB', 'GLsizeiptrARB', 'GLhandleARB'}
SIGNED_PTRSIZE = {'GLintptr', 'GLsizeiptr', 'GLintptrARB', 'GLsizeiptrARB'}
I64 = {'GLint64', 'GLuint64', 'GLint64EXT', 'GLuint64EXT'}
FLT = {'GLfloat', 'GLclampf'}
DBL = {'GLdouble', 'GLclampd'}

def argtypes(args):
    if args in ('', 'void', 'GLvoid'): return []
    out = []
    for a in args.split(','):
        a = a.strip()
        m = re.match(r'(.*?)\b(\w+)\s*(\[\d*\])?$', a)
        t = m.group(1).strip() if m and m.group(1).strip() else a
        if m and m.group(3): t += '*'
        out.append(re.sub(r'\s+', ' ', t.replace('*', ' * ')).strip())
    return out

def ctype(t): return t.replace(' * ', '*').replace(' *', '*')

lines = ['/* generated by tools/gen_gl.py from the SDK OpenGL headers: do not edit */', '#include "mac.h"',
         '#define GL_SILENCE_DEPRECATION', '#include <OpenGL/gl.h>', '#include <OpenGL/glext.h>', '#include "gl_rt.h"']
idx = 0; names = []
for name in sorted(fns):
    ret, args = fns[name]
    if name in MANUAL: continue
    ts = argtypes(args); ok = True; slot = 0; pre = []; call = []
    for k, t in enumerate(ts):
        base = t.replace('const ', '').strip()
        if '*' in t:
            if 'GLhandleARB' in base and base.count('*') == 1 and not t.startswith('const'):   # GLhandleARB *obj (out): 32-bit guest slots
                ok = False; break
            call.append('(%s)gl_ptr(ARG(%d))' % (ctype(t), slot)); slot += 1
        elif base in INT:
            if base == 'GLhandleARB': call.append('(GLhandleARB)(uintptr_t)ARG(%d)' % slot)
            elif base in SIGNED_PTRSIZE: call.append('(%s)(int32_t)ARG(%d)' % (base, slot))
            else: call.append('(%s)ARG(%d)' % (base, slot))
            slot += 1
        elif base in I64: call.append('(%s)ARG64(%d)' % (base, slot)); slot += 2
        elif base in FLT: call.append('ARGF(%d)' % slot); slot += 1
        elif base in DBL: call.append('ARGD(%d)' % slot); slot += 2
        else: ok = False; break
    rb = ret.replace('const ', '').strip()
    if not ok or '*' in ret or rb not in INT | FLT | DBL | I64 | {'void', 'GLvoid'}: continue
    proto = '%s (*)(%s)' % (ret, ', '.join(ctype(t) for t in ts) or 'void')
    invoke = '((%s)glp[%d])(%s)' % (proto, idx, ', '.join(call))
    if rb in ('void', 'GLvoid'): body = '%s; RETV();' % invoke
    elif rb in FLT or rb in DBL: body = 'RETD(%s);' % invoke
    elif rb in I64: body = 'RET64(%s);' % invoke
    elif rb == 'GLhandleARB': body = 'RET((uint32_t)(uintptr_t)%s);' % invoke
    else: body = 'RET(%s);' % invoke
    body = body.replace('RETV();', 'GL_CHECK("%s"); RETV();' % name) if 'RETV();' in body else body
    lines.append('IMP_AS(gl_%s, "%s") { GL_TRACE("%s"); %s }' % (name, name, name, body))
    lines.append('ALIAS(gl_%s, "_%s")' % (name, name))
    names.append(name); idx += 1
lines.append('const char *const gl_names[] = {%s};' % ', '.join('"%s"' % n for n in names))
lines.append('const unsigned gl_count = %d;' % len(names))
lines.append('void *glp[%d];' % max(1, len(names)))
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
print('%d GL entry points wrapped (%d in the headers, %d by hand)' % (len(names), len(fns), len(MANUAL)))
